#!/usr/bin/env python3
"""
Regenerate the "既存コンテンツ一覧" section of CLAUDE.md from data/contents.json.

Run: python3 scripts/sync_claude_md_inventory.py
Fails (exit 1) if CLAUDE.md was changed, so CI can detect drift.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENTS = ROOT / "data" / "contents.json"
CLAUDE_MD = ROOT / "CLAUDE.md"

START = "<!-- INVENTORY:START (auto-generated by scripts/sync_claude_md_inventory.py) -->"
END = "<!-- INVENTORY:END -->"


def build_section(items):
    skip = {"about", "contents", "log", "log.php"}
    by_cat = {}
    for c in items:
        page = c.get("page")
        if not page or page in skip:
            continue
        cat = c.get("category", "その他")
        by_cat.setdefault(cat, []).append(c)

    for cat in by_cat:
        by_cat[cat].sort(key=lambda c: (c.get("added") or "", c.get("page")))

    order = ["読み物", "遊べる", "眺める", "ガイド", "おまけ", "その他"]
    cats = [c for c in order if c in by_cat] + [c for c in by_cat if c not in order]

    total = sum(len(v) for v in by_cat.values())
    out = [START, "", f"## 既存コンテンツ一覧（被りチェック用・自動生成 / total={total}）", ""]
    out.append("> ⚠ ここは `scripts/sync_claude_md_inventory.py` が `data/contents.json` から再生成します。手で編集しないこと。新規ページ追加後は必ずスクリプトを実行(または `add` + `git push` 時にCIで再生成)。")
    out.append("")

    for cat in cats:
        out.append(f"### {cat}（{len(by_cat[cat])}件）")
        out.append("")
        for c in by_cat[cat]:
            title = c.get("title", "").strip()
            desc = (c.get("desc") or "").strip().replace("\n", " ")
            added = c.get("added") or "?"
            slug = c.get("page")
            out.append(f"- `{slug}` **{title}** — {desc}  _(added {added})_")
        out.append("")

    out.append("**カバー判定の使い方**: 新規アイデアが上の `desc` のキーワード/概念とかぶる場合は別案を出す。特にフィボナッチ/黄金比/螺旋/フラクタル/セルオートマトン/波/振動/カオス/流体/拡散はすでに複数ページがあるため、それらに分類されそうな新案は既存ページの説明文を必ず読んでから判断する。")
    out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    items = json.loads(CONTENTS.read_text(encoding="utf-8"))
    new_section = build_section(items)

    md = CLAUDE_MD.read_text(encoding="utf-8")

    if START in md and END in md:
        new_md = re.sub(
            re.escape(START) + r".*?" + re.escape(END),
            new_section,
            md,
            count=1,
            flags=re.DOTALL,
        )
    else:
        # First-time install: replace the legacy "## 既存コンテンツ一覧" section if present
        legacy = re.search(r"\n## 既存コンテンツ一覧.*?(?=\n## |\Z)", md, flags=re.DOTALL)
        if legacy:
            new_md = md[:legacy.start()] + "\n" + new_section + md[legacy.end():]
        else:
            new_md = md.rstrip() + "\n\n" + new_section + "\n"

    changed = new_md != md
    if changed:
        CLAUDE_MD.write_text(new_md, encoding="utf-8")
        print(f"updated CLAUDE.md ({len(items)} entries indexed)")
        sys.exit(1 if "--check" in sys.argv else 0)
    else:
        print("CLAUDE.md is up to date")
        sys.exit(0)


if __name__ == "__main__":
    main()
