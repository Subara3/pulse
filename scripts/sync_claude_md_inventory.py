#!/usr/bin/env python3
"""
Regenerate the "既存コンテンツ一覧" section of CLAUDE.md from data/contents.json.

Run: python3 scripts/sync_claude_md_inventory.py
Fails (exit 1) if CLAUDE.md was changed, so CI can detect drift.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENTS = ROOT / "data" / "contents.json"
CLAUDE_MD = ROOT / "CLAUDE.md"

START = "<!-- INVENTORY:START (auto-generated by scripts/sync_claude_md_inventory.py) -->"
END = "<!-- INVENTORY:END -->"


def build_section(items):
    skip = {"about", "contents"}

    # 12コレクションの並び順（includes/collections.php と揃えること）
    order = [
        ("chaos", "予測できないもの"), ("grow", "育つもの"), ("flow", "流れるもの"),
        ("swarm", "群れるもの"), ("lattice", "格子のもの"), ("number", "数えるもの"),
        ("curve", "描くもの"), ("fractal", "繰り返すもの"), ("light", "光るもの"),
        ("force", "引き合うもの"), ("tile", "敷き詰めるもの"), ("mind", "探すもの"),
    ]
    label = dict(order)

    by_group = {}
    for c in items:
        page = c.get("page")
        if not page or page in skip:
            continue
        by_group.setdefault(c.get("group") or "?", []).append(c)

    for g in by_group:
        by_group[g].sort(key=lambda c: (c.get("added") or "", c.get("page")))

    groups = [g for g, _ in order if g in by_group] + [
        g for g in by_group if g not in label
    ]

    total = sum(len(v) for v in by_group.values())
    out = [START, "", f"## 既存コンテンツ一覧（被りチェック用・自動生成 / total={total}）", ""]
    out.append(
        "> ここは `scripts/sync_claude_md_inventory.py` が `data/contents.json` から再生成します。"
        "手で編集しないこと。新規ページ追加後は必ずスクリプトを実行"
        "(または `add` + `git push` 時にCIで再生成)。"
    )
    out.append("")

    for g in groups:
        out.append(f"### {label.get(g, g)} / {g}（{len(by_group[g])}件）")
        out.append("")
        for c in by_group[g]:
            title = c.get("title", "").strip()
            desc = " ".join((c.get("desc") or "").split())
            added = c.get("added") or "?"
            slug = c.get("page")
            out.append(f"- `{slug}` **{title}** — {desc}  _(added {added})_")
        out.append("")

    # 統合済みの概念。ここを出しておかないと、消した概念を自動更新が作り直す
    # （2026-08-24 に cyclicca を消した直後、Day 208 で cyclic が再生成された）。
    merged_path = ROOT / "data" / "merged.json"
    if merged_path.exists():
        merged = json.loads(merged_path.read_text(encoding="utf-8"))
        out.append(f"### 統合済み・再作成しないこと（{len(merged)}件）")
        out.append("")
        out.append(
            "> 過去に「被り」として統合したページ。**同じ概念で新規ページを作らないこと。**"
            "既存ページを拡張するか、別の概念を選ぶ。"
        )
        out.append("")
        for old_page in sorted(merged):
            info = merged[old_page]
            concept = info.get("concept") or ""
            out.append(f"- `{old_page}` — {concept} → **`{info['to']}`** に統合済み（{info['why']}）")
        out.append("")

    out.append(
        "**カバー判定の使い方**: 新案を「画面では〇〇が起きていて、触ると△△になる」の 1 行に書き下し、"
        "該当コレクションの `desc` を全部読んで、同じ 1 行になるものが 1 つでもあれば新ページにしない"
        "（既存ページを磨く＝改修 Day）。式やアルゴリズムの名前が違っても見た目と手ざわりが同じなら被り。"
        "見栄えの選び方と改修 Day の手順は「題材の決め方」を参照。"
    )
    out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    items = json.loads(CONTENTS.read_text(encoding="utf-8"))
    new_section = build_section(items)

    md = CLAUDE_MD.read_text(encoding="utf-8")

    if START in md and END in md:
        new_md = re.sub(
            re.escape(START) + r".*?" + re.escape(END),
            new_section,
            md,
            count=1,
            flags=re.DOTALL,
        )
    else:
        # First-time install: replace the legacy "## 既存コンテンツ一覧" section if present
        legacy = re.search(r"\n## 既存コンテンツ一覧.*?(?=\n## |\Z)", md, flags=re.DOTALL)
        if legacy:
            new_md = md[:legacy.start()] + "\n" + new_section + md[legacy.end():]
        else:
            new_md = md.rstrip() + "\n\n" + new_section + "\n"

    changed = new_md != md
    if changed:
        CLAUDE_MD.write_text(new_md, encoding="utf-8")
        print(f"updated CLAUDE.md ({len(items)} entries indexed)")
        sys.exit(1 if "--check" in sys.argv else 0)
    else:
        print("CLAUDE.md is up to date")
        sys.exit(0)


if __name__ == "__main__":
    main()
